"""M7 probe 4: the OptiX denoiser inside a Houdini process that uses CUDA and
OptiX itself.

hython, isolated (tests/houdini/run_hython.ps1):

    run_hython.ps1 -Script inproc_probe.py <spike.dll> <noisy.exr> <out_dir>

1. Houdini's own OptiX denoiser runs first, through a COP2 "aidenoise" node
   (TIL_DenoiseOptix7, which creates its own CUDA context).
2. The spike DLL (prototypes/optix_denoise_spike.cpp built with
   `build_spike.bat <dir> dll`) is loaded with ctypes and denoises the same
   EXR in the same process with the device's primary context; it prints the
   primary context's state before it retains it.
3. Houdini's denoiser runs again (does it still work after ours?), then the
   spike once more (warm process).
Prints which NVIDIA DLLs are loaded at each step and the times.
"""
import ctypes
import os
import sys
import time

import hou

dll_path, noisy, out_dir = sys.argv[1], sys.argv[2], sys.argv[3]
os.makedirs(out_dir, exist_ok=True)
k32 = ctypes.WinDLL('kernel32', use_last_error=True)
k32.GetModuleHandleW.restype = ctypes.c_void_p
k32.GetModuleHandleW.argtypes = [ctypes.c_wchar_p]


def loaded():
    return [n for n in ('nvcuda.dll', 'nvoptix.dll', 'TIL_DenoiseOptix7.dll', 'OpenImageDenoise.dll')
            if k32.GetModuleHandleW(n)]


def log(*a):
    print(*a, flush=True)


log('start: loaded', loaded())

# --- 1. Houdini's OptiX denoiser through COP2 ------------------------------
img = hou.node('/img')
net = img.createNode('img', 'probe')
f = net.createNode('file', 'noisy')
f.parm('filename1').set(noisy)
dn = net.createNode('aidenoise', 'dn')
dn.setInput(0, f)
log('aidenoise parms:', [(p.name(), p.eval()) for p in dn.parms()][:20])
engine = sys.argv[4] if len(sys.argv) > 4 else 'optix'
dn.parm('denoiser').set(engine)  # the menu is generated by a script, so set the token
log('denoiser =', dn.parm('denoiser').eval())
log('planes of file COP:', f.planes())


def cook_houdini(tag):
    t = time.perf_counter()
    try:
        dn.cook(force=True)
        px = dn.allPixels('C')
        err = dn.errors()
    except Exception as e:
        px, err = None, str(e)
    log('%s: Houdini aidenoise cook %.1f ms, %s pixels, errors %r, loaded %s' % (
        tag, (time.perf_counter() - t) * 1000, len(px) if px else None, err, loaded()))


cook_houdini('first')

# --- 2. the spike in the same process ---------------------------------------
os.add_dll_directory(os.path.dirname(dll_path))
spike = ctypes.CDLL(dll_path)
spike.spike_main.argtypes = [ctypes.c_int, ctypes.POINTER(ctypes.c_char_p)]
spike.spike_main.restype = ctypes.c_int


def run_spike(tag, out):
    args = [b'spike', b'--in', noisy.encode(), b'--out', out.encode(), b'--iters', b'10']
    argv = (ctypes.c_char_p * len(args))(*args)
    t = time.perf_counter()
    rc = spike.spike_main(len(args), argv)
    log('%s: spike rc %d, %.1f ms, loaded %s' % (tag, rc, (time.perf_counter() - t) * 1000, loaded()))


run_spike('spike #1', os.path.join(out_dir, 'inproc_1.exr'))
cook_houdini('after spike')
run_spike('spike #2', os.path.join(out_dir, 'inproc_2.exr'))
log('done')
