"""Writes the scenes of tests/husk/check_karma_p9b.py (docs/design/M11-P9b.md):
nested dielectrics (karma:object:dielectricpriority) and light portals
(karma:object:isportal, portaldomelights, the dome's portalmisbias).

The geometry layers (geo_*.usda) are written as text; each case is a layer
over one of them holding what Houdini's own LOPs author: a Karma Render
Settings LOP (karmarendersettings) and, for the per-object properties, a
Render Geometry Settings LOP with values on its Karma tab. The generated
files are committed; rebuild them after a Houdini update with an isolated
hython:

  powershell -ExecutionPolicy Bypass -File tests\\houdini\\run_hython.ps1 -Script tests\\husk\\karma_p9b\\build_karma_p9b.py

Nested dielectrics: glass A (index 1.5, absorbing green over a unit depth)
and B (index 2, absorbing blue), seen through at normal incidence by an
orthographic camera over an emitter, so red is the interfaces' Fresnel
loss, green and blue the lengths inside A and B; A over a B that overlaps
its lower half (overlap), or a B inside A (contain). Oblique: the same
overlap as wide slabs seen at 45 degrees over the edge of an emitter, whose
image position gives the refracted direction. Shadow: the contain stack
lit by a sun at 45 degrees over a floor (fake caustics).

Portals: a closed room (walls, floor, ceiling of a grey diffuse) with a
window in its +x wall, lit only by a white dome through it; a camera under
the ceiling looks down. room2 has a second window (-x) without a portal;
the two-dome scenes light it red and blue; outside looks at the window
from outside over a ground plane; sun adds a distant light through the
window.
"""

import os
import sys

import hou
from pxr import Sdf

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = sys.argv[1] if len(sys.argv) > 1 else HERE

HEAD = '''#usda 1.0
(
    defaultPrim = "World"
    metersPerUnit = 1
    upAxis = "Y"
)

# Generated by build_karma_p9b.py: geometry of tests/husk/check_karma_p9b.py.
'''

MAT = '''    def Material "%(name)s"
    {
        token outputs:mtlx:surface.connect = </Looks/%(name)s/s.outputs:out>
        def Shader "s"
        {
            uniform token info:id = "ND_standard_surface_surfaceshader"
%(inputs)s
            token outputs:out
        }
    }
'''


def mat(name, **inputs):
    lines = []
    for k, v in inputs.items():
        if isinstance(v, tuple):
            lines.append('            color3f inputs:%s = (%g, %g, %g)' % (k, v[0], v[1], v[2]))
        else:
            lines.append('            float inputs:%s = %g' % (k, v))
    return MAT % dict(name=name, inputs='\n'.join(lines))


GLASS_A = mat('glassA', base=0, specular=1, specular_IOR=1.5, specular_roughness=0, transmission=1,
              transmission_color=(1, 0.5, 1), transmission_depth=1)
GLASS_B = mat('glassB', base=0, specular=1, specular_IOR=2.0, specular_roughness=0, transmission=1,
              transmission_color=(1, 1, 0.5), transmission_depth=1)
EMIT = mat('emit', base=0, specular=0, emission=1, emission_color=(1, 1, 1))
GREY = mat('grey', base=1, base_color=(0.5, 0.5, 0.5), specular=0)


def box(name, x0, x1, y0, y1, z0, z1, m):
    return '''    def Cube "%s" (prepend apiSchemas = ["MaterialBindingAPI"])
    {
        double size = 1
        float3[] extent = [(-0.5, -0.5, -0.5), (0.5, 0.5, 0.5)]
        double3 xformOp:translate = (%g, %g, %g)
        float3 xformOp:scale = (%g, %g, %g)
        uniform token[] xformOpOrder = ["xformOp:translate", "xformOp:scale"]
        rel material:binding = </Looks/%s>
    }
''' % (name, (x0 + x1) / 2, (y0 + y1) / 2, (z0 + z1) / 2, x1 - x0, y1 - y0, z1 - z0, m)


def quad(name, pts, m):
    xs, ys, zs = [p[0] for p in pts], [p[1] for p in pts], [p[2] for p in pts]
    return '''    def Mesh "%s" (prepend apiSchemas = ["MaterialBindingAPI"])
    {
        int[] faceVertexCounts = [4]
        int[] faceVertexIndices = [0, 1, 2, 3]
        point3f[] points = [%s]
        float3[] extent = [(%g, %g, %g), (%g, %g, %g)]
        uniform bool doubleSided = 1
        uniform token subdivisionScheme = "none"
        rel material:binding = </Looks/%s>
    }
''' % (name, ', '.join('(%g, %g, %g)' % p for p in pts), min(xs), min(ys), min(zs), max(xs), max(ys), max(zs), m)


def hquad(name, x0, x1, y, z0, z1, m):
    return quad(name, [(x0, y, z1), (x1, y, z1), (x1, y, z0), (x0, y, z0)], m)


def ortho(tx, ty, tz, rx, hap, vap):
    return '''    def Camera "cam"
    {
        token projection = "orthographic"
        float horizontalAperture = %g
        float verticalAperture = %g
        float2 clippingRange = (0.1, 100)
        double3 xformOp:translate = (%g, %g, %g)
        float3 xformOp:rotateXYZ = (%g, 0, 0)
        uniform token[] xformOpOrder = ["xformOp:translate", "xformOp:rotateXYZ"]
    }
''' % (hap, vap, tx, ty, tz, rx)


def write(name, prims, mats):
    with open(os.path.join(OUT, name), 'w', newline='\n') as f:
        f.write(HEAD + 'def Xform "World"\n{\n' + ''.join(prims) + '}\n\ndef Scope "Looks"\n{\n' + ''.join(mats) + '}\n')


# --- Nested dielectrics -------------------------------------------------------
TOP = ortho(0, 10, 0, -90, 20, 20)  # 2 x 2 units
EMITTER = hquad('emitter', -4, 4, -3, -4, 4, 'emit')
