write('geo_shadow.usda', [hquad('floor', -10, 12, -3, -10, 12, 'grey'), box('A', -4, 4, -1, 2, -3, 3, 'glassA'),
                          box('B', -3, 3, 0, 1, -2.5, 2.5, 'glassB'), SUN45, ortho(5.5, 10, 3, -90, 30, 90)],
      [GREY, GLASS_A, GLASS_B])


# --- Light portals ------------------------------------------------------------
def wall_x(name, x, hole):
    if not hole:
        return quad(name, [(x, 0, -2), (x, 0, 2), (x, 3, 2), (x, 3, -2)], 'grey')
    return ''.join([
        quad(name + '_lo', [(x, 0, -2), (x, 0, 2), (x, 1, 2), (x, 1, -2)], 'grey'),
        quad(name + '_hi', [(x, 2, -2), (x, 2, 2), (x, 3, 2), (x, 3, -2)], 'grey'),
        quad(name + '_l', [(x, 1, -2), (x, 1, -0.75), (x, 2, -0.75), (x, 2, -2)], 'grey'),
        quad(name + '_r', [(x, 1, 0.75), (x, 1, 2), (x, 2, 2), (x, 2, 0.75)], 'grey'),
    ])


def room(xm_window=False):
    return ''.join([
        quad('floor', [(-2, 0, -2), (2, 0, -2), (2, 0, 2), (-2, 0, 2)], 'grey'),
        quad('ceiling', [(-2, 3, -2), (-2, 3, 2), (2, 3, 2), (2, 3, -2)], 'grey'),
        quad('wall_zp', [(-2, 0, 2), (2, 0, 2), (2, 3, 2), (-2, 3, 2)], 'grey'),
        quad('wall_zm', [(-2, 0, -2), (-2, 3, -2), (2, 3, -2), (2, 0, -2)], 'grey'),
        wall_x('wall_xp', 2, True),
        wall_x('wall_xm', -2, xm_window),
    ])


PORTAL = quad('portal', [(2, 1, -0.75), (2, 1, 0.75), (2, 2, 0.75), (2, 2, -0.75)], 'grey')


def dome(name, color):
    return '''    def DomeLight "%s"
    {
        float inputs:intensity = 1
        color3f inputs:color = (%g, %g, %g)
    }
''' % (name, color[0], color[1], color[2])


