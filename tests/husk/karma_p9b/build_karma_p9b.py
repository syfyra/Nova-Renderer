def prio(a, b, extra=None):
    objs = []
    for prim, p in (('/World/A', a), ('/World/B', b)):
        props = {} if p is None else {'dielectricpriority': p}
        props.update(extra or {})
        if props:
            objs.append((prim, props))
    return objs


