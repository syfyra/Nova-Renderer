"""Writes the scenes of tests/husk/check_karma_guiding.py (docs/design/M11-P9c.md):
one USDA per case, holding what a Karma Render Settings LOP
(karmarendersettings) authors over one of the geo_*.usda scenes (a
subLayer). The LOP shows two of Karma's five guiding properties (Enable
Indirect Guiding, Indirect Training Samples); the other three
(guiding_components, guiding_deterministic, guiding_clearbuffers) are
written onto the same RenderSettings prim with the names and types of
Karma's registry, as an Edit Properties LOP would. The generated files are
committed; rebuild them after a Houdini update with an isolated hython:

  powershell -ExecutionPolicy Bypass -File tests\\houdini\\run_hython.ps1 -Script tests\\husk\\karma_guiding\\build_karma_guiding.py

Cases: name -> (geometry, LOP parameters, extra Karma properties). Every
case renders 32 Path Traced samples with a uniform oracle, no colour limits
(clamping would make the mean depend on the noise), so guiding changes only
the noise.
"""

import os
import sys

import hou
from pxr import Sdf

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = sys.argv[1] if len(sys.argv) > 1 else HERE

PATH = {'convergence_mode': 'Path Traced', 'oracle': 'uniform', 'pathtracedsamples': 32,
        'colorlimit': 1e6, 'colorlimitindirect': 1e6}
ROOM = ('geo_room.usda', (160, 120), PATH)
FOG = ('geo_roomfog.usda', (160, 120), dict(PATH, volumelimit=1))
GUIDE = {'guiding_enable': 1}

CASES = {
    # A room lit through a window: guiding off and on (training throughout).
    'room_off': (ROOM, {}, {}),
    'room_on': (ROOM, GUIDE, {}),
    # Training for the first 8 samples only, then the frozen field; and the
    # same with the training samples discarded from the image.
    'room_train': (ROOM, dict(GUIDE, guiding_samples=8), {}),
    'room_clear': (ROOM, dict(GUIDE, guiding_samples=8), {'guiding_clearbuffers': True}),
    # Components: glossy reflection only (the room is diffuse: nothing to
    # guide); deterministic mode.
    'room_reflect': (ROOM, GUIDE, {'guiding_components': 'reflect'}),
    'room_det': (ROOM, GUIDE, {'guiding_deterministic': True}),
    # The room filled with fog lit indirectly: off, on, and with volumes
    # left out of the components.
    'fog_off': (FOG, {}, {}),
    'fog_on': (FOG, GUIDE, {}),
    'fog_diffuse': (FOG, GUIDE, {'guiding_components': 'diffuse'}),
}

EXTRA_TYPES = {'guiding_components': Sdf.ValueTypeNames.String, 'guiding_deterministic': Sdf.ValueTypeNames.Bool,
               'guiding_clearbuffers': Sdf.ValueTypeNames.Bool}


def build(name, geo, res, base, settings, extra):
    stage = hou.node('/stage')
    for child in stage.children():
        child.destroy()
    last = stage.createNode('sublayer', 'geometry')
    last.parm('filepath1').set(os.path.join(HERE, geo).replace('\\', '/'))
    krs = stage.createNode('karmarendersettings', 'karma')
    krs.setInput(0, last)
    krs.parm('primpath').set('/Render/rendersettings')
    krs.parm('renderproductsparentprimpath').set('/Render/Products')
    krs.parm('rendervarsparentprimpath').set('/Render/Vars')
    krs.parm('picture').set('karma_guiding.exr')  # husk -o replaces it
    krs.parm('camera').set('/World/cam')
    for parm, value in (('resolutionx', res[0]), ('resolutiony', res[1])):
        p = krs.parm(parm)
        p.lock(False)
        p.deleteAllKeyframes()  # the auto-height expression
        p.set(value)
    for parm, value in dict(base, **settings).items():
        p = krs.parm(parm)
        if p is None:
            raise RuntimeError('Karma Render Settings has no parameter %s' % parm)
        p.set(value)
    krs.cook(force=True)
    if krs.errors():
        raise RuntimeError('%s: %s' % (name, krs.errors()))
    flat = krs.stage().Flatten()
    layer = Sdf.Layer.CreateAnonymous('.usda')
    Sdf.CopySpec(flat, '/Render', layer, '/Render')
    prim = layer.GetPrimAtPath('/Render/rendersettings')
    for prop, value in extra.items():
        attr = Sdf.AttributeSpec(prim, 'karma:global:' + prop, EXTRA_TYPES[prop])
        attr.default = value

    def strip(path):  # Houdini's editor bookkeeping
        spec = layer.GetObjectAtPath(path)
        if spec is not None and 'customData' in spec.ListInfoKeys():
            spec.ClearInfo('customData')
    layer.Traverse(Sdf.Path.absoluteRootPath, strip)
    layer.comment = 'Generated by build_karma_guiding.py (case %s): what Houdini\'s LOPs author.' % name
    layer.subLayerPaths.append('./' + geo)
    for key in ('renderSettingsPrimPath', 'framesPerSecond', 'timeCodesPerSecond', 'metersPerUnit', 'upAxis'):
        if flat.pseudoRoot.HasInfo(key):
            layer.pseudoRoot.SetInfo(key, flat.pseudoRoot.GetInfo(key))
    path = os.path.join(OUT, name + '.usda')
    layer.Export(path)
    return path


for case, ((geo, res, base), settings, extra) in CASES.items():
    print('wrote', build(case, geo, res, base, settings, extra))
