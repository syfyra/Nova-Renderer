def read(oiio, np, path):
    image = oiio.ImageInput.open(path)
    if not image:
        return None
    spec = image.spec()
    px = np.asarray(image.read_image(0, 0, 0, spec.nchannels, oiio.FLOAT)).reshape(spec.height, spec.width, -1)
    image.close()
    return px


def views():
    out = {}
    for key in list(KARMA) + list(MODEL):
        name, view = key.split(":")
        out.setdefault(name, set()).add(view)
