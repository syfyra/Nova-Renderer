"""Generates Nova's Solaris parameter files from houdini/tools/nova_settings.json
(docs/design/M4.md 3.7, docs/research/m4/render-settings-ui.md 5.1):

  houdini/package/soho/parameters/HdNovaRendererPlugin_Global.ds    Nova tab of the Render Settings LOP
  houdini/package/soho/parameters/HdNovaRendererPlugin_Geometry.ds  Nova tab of the Render Geometry Settings LOP
  houdini/package/soho/parameters/HdNovaRendererPlugin_Viewport.ds  the viewport's display options
  houdini/package/soho/parameters/HdNovaXpuRendererPlugin_Viewport.ds  the same for Nova XPU

Run with hython (parameter names come from hou.text.encodeParm), in an
isolated environment:

  powershell -ExecutionPolicy Bypass -File tests\\houdini\\run_hython.ps1 -Script houdini\\tools\\gen_nova_ds.py [outdir]

The files are committed; tests/houdini/test_solaris_ui.py regenerates them
into a temporary directory and compares.
"""

import json
import os
import sys

import hou

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, '..', 'package', 'soho', 'parameters')
PLUGIN = 'HdNovaRendererPlugin'
enc = hou.text.encodeParm

HEADER = '''/// Automatically generated by houdini/tools/gen_nova_ds.py from
/// houdini/tools/nova_settings.json: do not edit by hand.
/// %s

#include "$HFS/houdini/soho/parameters/CommonMacros.ds"
'''

PARM_TYPE = {'int': 'int', 'float': 'float', 'bool': 'toggle', 'token': 'string', 'string': 'string'}


def literal(setting):
    v = setting['default']
    if setting['type'] == 'bool':
        return '1' if v else '0'
    if setting['type'] in ('token', 'string'):
        return '"%s"' % v
    if setting['type'] == 'float':
        return repr(float(v))
    return str(int(v))


def quote(text):
    return text.replace('\\', '\\\\').replace('"', '\\"')


def control_parm(attr, setting, indent):
    name = enc(attr + '_control')
    pad = ' ' * indent
    return [
        pad + 'parm {',
        pad + '    name    "%s"' % name,
        pad + '    label   "%s"' % quote(setting['label']),
        pad + '    type    string',
        pad + '    default { "none" }',
        pad + '    menujoin {',
        pad + '        [ "import loputils" ]',
        pad + '        [ "return loputils.createEditPropertiesControlMenu(kwargs, \'%s\')" ]' % setting['type'],
        pad + '        language python',
        pad + '    }',
        pad + '    parmtag { "sidefx::look" "icon" }',
        pad + '}',
    ]


def value_parm(attr, setting, indent, control, uiscope):
    name = enc(attr)
    pad = ' ' * indent
    lines = [
        pad + 'parm {',
        pad + '    name    "%s"' % name,
        pad + '    label   "%s"' % quote(setting['label']),
        pad + '    type    %s' % PARM_TYPE[setting['type']],
        pad + '    size    1',
        pad + '    default { %s }' % literal(setting),
    ]
    if 'range' in setting:
        lo, hi = setting['range']
        lines.append(pad + '    range   { %s %s }' % (lo, hi))
    if 'menu' in setting:
        lines.append(pad + '    menu {')
        for value, label in setting['menu']:
            lines.append(pad + '        "%s" "%s"' % (value, quote(label)))
        lines.append(pad + '    }')
    lines += [
        pad + '    help    "%s"' % quote(setting['help']),
        pad + '    parmtag { "spare_category" "%s" }' % setting['section'],
        pad + '    parmtag { "uiscope" "%s" }' % (uiscope + ' toolbar' if uiscope == 'viewport' and setting.get('toolbar')
                                                    else uiscope),
        pad + '    parmtag { "usdvaluetype" "%s" }' % setting['type'],
    ]
    if uiscope == 'viewport' and setting.get('icon'):
        lines.append(pad + '    parmtag { "uiicon" %s }' % setting['icon'])
    if control:
        c = enc(attr + '_control')
        lines.append(pad + '    disablewhen "{ %s == block } { %s == none }"' % (c, c))
    lines.append(pad + '}')
    return lines


def sections(settings):
    order = []
    for s in settings:
        if s['section'] not in order:
            order.append(s['section'])
    return [(name, [s for s in settings if s['section'] == name]) for name in order]


def collapsible(prefix, title, settings, attr, indent, control, uiscope):
    pad = ' ' * indent
    lines = [pad + 'groupcollapsible {',
             pad + '    name    "%s_%s"' % (prefix, title.lower().replace(' ', '_')),
             pad + '    label   "%s"' % title,
             pad + '    grouptag { "group_default" "1" }']
    for s in settings:
        if control:
            lines += control_parm(attr(s), s, indent + 4)
        lines += value_parm(attr(s), s, indent + 4, control, uiscope)
    lines.append(pad + '}')
    return lines


def write(name, lines, what, plugin=PLUGIN):
    path = os.path.join(OUT, '%s_%s.ds' % (plugin, name))
    with open(path, 'w', newline='\n') as f:
        f.write(HEADER % what)
        f.write('\n'.join(lines) + '\n')
    print('wrote', os.path.normpath(path))


def main():
    with open(os.path.join(HERE, 'nova_settings.json')) as f:
        table = json.load(f)['settings']
    os.makedirs(OUT, exist_ok=True)
    top = ['{', '    name    "nova"', '    label   "Nova"',
           '    parmtag { spare_opfilter "!!SHOP/PROPERTIES!!" }', '    parmtag { spare_classtags "render" }']

    # Global: the render settings, object defaults in their own sub-tab.
    render = [s for s in table if 'global' in s['scopes'] and not s['key'].startswith('nova:object:')]
    objects = [s for s in table if 'global' in s['scopes'] and s['key'].startswith('nova:object:')]
    lines = list(top)
    lines += ['    group {', '        name    "nova_global"', '        label   "Rendering"']
    for title, group in sections(render):
        lines += collapsible('nova', title, group, lambda s: s['key'], 8, True, 'None')
    lines += ['    }', '    group {', '        name    "nova_object_defaults"',
              '        label   "Default Geometry Settings"']
    for title, group in sections(objects):
        lines += collapsible('nova_object', title, group, lambda s: s['key'], 8, True, 'None')
    lines += ['    }', '}']
    write('Global', lines, 'Render Settings LOP: the Nova tab.')

    # Geometry: constant primvars per prim.
    geometry = [s for s in table if 'geometry' in s['scopes']]
    lines = list(top)
    for title, group in sections(geometry):
        lines += collapsible('nova_geo', title, group, lambda s: 'primvars:' + s['key'], 4, True, 'None')
    lines.append('}')
    write('Geometry', lines, 'Render Geometry Settings LOP: per-object properties (constant primvars).')

    # Viewport: the interactive subset, values only.
    viewport = [s for s in table if 'viewport' in s['scopes']]
    lines = list(top)
    for title, group in sections(viewport):
        lines += collapsible('nova_vp', title, group, lambda s: s['key'], 4, False, 'viewport')
    lines.append('}')
    write('Viewport', lines, 'Viewport display options: the interactive subset.')
    # Nova XPU (docs/design/M10.md D1) shares the settings; as Karma XPU it has
    # a viewport file of its own.
    write('Viewport', lines, 'Viewport display options of Nova XPU: the interactive subset.', 'HdNovaXpuRendererPlugin')


main()
